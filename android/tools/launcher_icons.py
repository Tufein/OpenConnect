#!/usr/bin/env python3
"""Writes the launcher icons the app lets you choose between (Settings, App icon).

Every icon is an adaptive icon: a solid background, a pixel-art foreground and a one-colour version for the themed icons
of Android 13 and later. The art is read from PixelIcons.kt, so the icons are made from the same grids that the app draws
(the 16 by 12 logo and the 12 by 12 star and stopwatch). The colours below are the same ones as in `AppIcon.kt`: when
you change one, change the other. The first icon ("handheld") has hand-made background and foreground files and is not
written here. Run from the repository root:  python3 android/tools/launcher_icons.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "app" / "src" / "main"
RES = ROOT / "res"
KOTLIN = (ROOT / "kotlin" / "nl" / "tufein" / "openconnect" / "ui" / "PixelIcons.kt").read_text()


def grid(name: str) -> list[str]:
    m = re.search(r"val %s(?:: List<String>)? = (?:PixelArt\(\s*)?listOf\((.*?)\)" % name, KOTLIN, re.S)
    return re.findall(r'"([^"]*)"', m.group(1))


LOGO = grid("Logo")
STAR = grid("Star")
STOPWATCH = grid("Stopwatch")

# key: (art, background, colours by character). For the heart: # outline, o fill, y shine, w pulse. Others: # only.
ICONS = {
    "night": ("heart", 0x131210, {"#": 0xF0E9D6, "o": 0xFF7A3D, "y": 0xFFD23F, "w": 0xF0E9D6}),
    "gameboy": ("heart", 0x9BBC0F, {"#": 0x0F380F, "o": 0x306230, "y": 0x8BAC0F, "w": 0xCADC9F}),
    "amber": ("heart", 0x0D0900, {"#": 0xFFE2A8, "o": 0xFFB000, "y": 0xFFD45C, "w": 0x0D0900}),
    "synthwave": ("heart", 0x14061F, {"#": 0x00E5FF, "o": 0xFF4FB8, "y": 0xFFD166, "w": 0xFFFFFF}),
    "candy": ("heart", 0xFFEFF8, {"#": 0x3A1030, "o": 0xFF7EB6, "y": 0xFFFFFF, "w": 0x3A1030}),
    "star": ("star", 0x1B2A5C, {"#": 0xFFD23F}),
    "stopwatch": ("stopwatch", 0x0D2233, {"#": 0x29B6F6}),
}


def argb(c: int) -> str:
    return "#FF%06X" % c


def paths(rows: list[str], unit: int, x0: int, y0: int, chars: dict[str, int]) -> str:
    """One <path> per colour, one `M x,y h w v h h-w z` square run per row run."""
    out = []
    for ch, colour in chars.items():
        d = []
        for y, row in enumerate(rows):
            x = 0
            while x < len(row):
                if row[x] == ch:
                    start = x
                    while x < len(row) and row[x] == ch:
                        x += 1
                    d.append("M%d,%dh%dv%dh-%dz" % (x0 + start * unit, y0 + y * unit, (x - start) * unit, unit, (x - start) * unit))
                else:
                    x += 1
        if d:
            out.append('    <path\n        android:fillColor="%s"\n        android:pathData="%s" />' % (argb(colour), " ".join(d)))
    return "\n".join(out)


HEAD = """<?xml version="1.0" encoding="utf-8"?>
<!-- %s Generated by android/tools/launcher_icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
"""


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def main() -> None:
    for key, (art, background, chars) in ICONS.items():
        rows, unit = {"heart": (LOGO, 4), "star": (STAR, 5), "stopwatch": (STOPWATCH, 5)}[art]
        w, h = max(len(r) for r in rows), len(rows)
        x0, y0 = (108 - w * unit) // 2, (108 - h * unit) // 2
        write(RES / "drawable" / f"ic_launcher_{key}_foreground.xml", HEAD % f"The {key} icon: the foreground." + paths(rows, unit, x0, y0, chars) + "\n</vector>\n")
        write(
            RES / "drawable" / f"ic_launcher_{key}_background.xml",
            HEAD % f"The {key} icon: the background." + '    <path\n        android:fillColor="%s"\n        android:pathData="M0,0h108v108h-108z" />\n</vector>\n' % argb(background),
        )
        mono = "ic_launcher_monochrome" if art == "heart" else f"ic_launcher_monochrome_{art}"
        if art != "heart":
            body = paths(rows, unit, x0, y0, {"#": 0x000000})
            write(RES / "drawable" / f"{mono}.xml", HEAD % f"The {art} in one colour, for the themed icons of Android 13 and later." + body + "\n</vector>\n")
        write(
            RES / "mipmap-anydpi-v26" / f"ic_launcher_{key}.xml",
            '<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            f'    <background android:drawable="@drawable/ic_launcher_{key}_background" />\n'
            f'    <foreground android:drawable="@drawable/ic_launcher_{key}_foreground" />\n'
            f'    <monochrome android:drawable="@drawable/{mono}" />\n</adaptive-icon>\n',
        )
        print("wrote", key)


if __name__ == "__main__":
    main()
