#!/usr/bin/env python3
"""Writes the launcher icons the app lets you choose between (Settings, App icon).

Every icon is an adaptive icon: a solid background, a smooth vector foreground and a one-colour version for the themed
icons of Android 13 and later. There is one mark for the six heart variants (a rounded heart with a pulse line) and two
quieter marks of their own for "star" and "stopwatch". All drawings stay inside the central 66 units of the 108 unit
viewport, the safe zone of an adaptive icon, and use thick round strokes so nothing turns into a smudge at 48 dp.

The background colours below are the same ones as in `AppIcon.kt`: when you change one, change the other. The first icon
("handheld") writes the base `ic_launcher*` files; the others write `ic_launcher_<key>*`. Run from the repository root:
    python3 android/tools/launcher_icons.py
"""
from pathlib import Path

RES = Path(__file__).resolve().parents[1] / "app" / "src" / "main" / "res"
DRAWABLE = RES / "drawable"
MIPMAP = RES / "mipmap-anydpi-v26"

HEAD = """<?xml version="1.0" encoding="utf-8"?>
<!-- %s Generated by android/tools/launcher_icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
"""

TAIL = """</vector>
"""

# The rounded heart, its pulse and the two own marks. The numbers are the 108-unit grid; the heart spans x 27-81 and
# y 28-78, and the 6-unit stroke keeps the whole drawing inside x 24-84 and y 25-81.
HEART = """    <path
        android:fillColor="%(fill)s"
        android:strokeColor="%(ink)s"
        android:strokeWidth="6"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:pathData="M54,78C46,70 27,56 27,42C27,33 33,28 40,28C46,28 51,31 54,37C57,31 62,28 68,28C75,28 81,33 81,42C81,56 62,70 54,78Z" />
    <path
        android:fillColor="#00000000"
        android:strokeColor="%(ink)s"
        android:strokeWidth="5.5"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:pathData="M41,56L46,56L50,48L56,65L61,52L65,56L68,56" />
"""

STAR = """    <path
        android:fillColor="%(fill)s"
        android:strokeColor="%(ink)s"
        android:strokeWidth="6"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:pathData="M54,25L62.5,42L81,44.5L67.5,57.5L71,76L54,66.5L37,76L40.5,57.5L27,44.5L45.5,42Z" />
"""

STOPWATCH = """    <path
        android:fillColor="%(fill)s"
        android:strokeColor="%(ink)s"
        android:strokeWidth="6"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:pathData="M32,57A22,22 0 1 1 76,57A22,22 0 1 1 32,57Z" />
    <path
        android:fillColor="%(fill)s"
        android:strokeColor="%(ink)s"
        android:strokeWidth="5.5"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:pathData="M47,26L61,26L61,36L47,36Z" />
    <path
        android:fillColor="#00000000"
        android:strokeColor="%(ink)s"
        android:strokeWidth="5.5"
        android:strokeLineCap="round"
        android:pathData="M69,42L75,37" />
    <path
        android:fillColor="#00000000"
        android:strokeColor="%(ink)s"
        android:strokeWidth="5"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:pathData="M54,57L54,46M54,57L64,61" />
"""

# key: (shape, background, fill, ink). The two own marks keep their shape but use the same quiet colours.
ICONS = {
    "handheld": ("heart", 0xF4EFE4, 0xC9D5B8, 0x3D4A32),
    "night": ("heart", 0x12150F, 0x3E4A35, 0xF2EDE1),
    "gameboy": ("heart", 0x263B2C, 0x617B56, 0xEFF3E8),
    "amber": ("heart", 0x251B11, 0x8A6A3E, 0xF6ECDD),
    "synthwave": ("heart", 0x1A1424, 0x574968, 0xF1ECE4),
    "candy": ("heart", 0xF5EDE7, 0xE3B6B1, 0x5B3B3A),
    "star": ("star", 0x1D2821, 0xD8BE93, 0xD8BE93),
    "stopwatch": ("stopwatch", 0xEEEAE0, 0xD7E0CE, 0x3C4A40),
}

SHAPES = {"heart": HEART, "star": STAR, "stopwatch": STOPWATCH}
MONOCHROME = {
    "heart": ("ic_launcher_monochrome", "#00000000", "#FFFFFFFF"),
    "star": ("ic_launcher_monochrome_star", "#FFFFFFFF", "#FFFFFFFF"),
    "stopwatch": ("ic_launcher_monochrome_stopwatch", "#00000000", "#FFFFFFFF"),
}


def argb(value: int) -> str:
    return "#FF%06X" % value


def body(shape: str, fill: str, ink: str) -> str:
    return SHAPES[shape] % {"fill": fill, "ink": ink}


def base(key: str) -> str:
    return "ic_launcher" if key == "handheld" else f"ic_launcher_{key}"


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def adaptive(key: str, shape: str) -> str:
    name = base(key)
    mono = MONOCHROME[shape][0]
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        f'    <background android:drawable="@drawable/{name}_background" />\n'
        f'    <foreground android:drawable="@drawable/{name}_foreground" />\n'
        f'    <monochrome android:drawable="@drawable/{mono}" />\n'
        "</adaptive-icon>\n"
    )


def main() -> None:
    written_mono = set()
    for key, (shape, background, fill, ink) in ICONS.items():
        name = base(key)
        write(
            DRAWABLE / f"{name}_foreground.xml",
            (HEAD % f"The {key} icon: the smooth vector foreground.")
            + body(shape, argb(fill), argb(ink))
            + TAIL,
        )
        write(
            DRAWABLE / f"{name}_background.xml",
            (HEAD % f"The {key} icon: the background.")
            + ('    <path\n        android:fillColor="%s"\n        android:pathData="M0,0h108v108h-108z" />\n' % argb(background))
            + TAIL,
        )
        if shape not in written_mono:
            mono_name, mono_fill, mono_ink = MONOCHROME[shape]
            write(
                DRAWABLE / f"{mono_name}.xml",
                (HEAD % f"The {shape} in one colour, for the themed icons of Android 13 and later.")
                + body(shape, mono_fill, mono_ink)
                + TAIL,
            )
            written_mono.add(shape)

        if key == "handheld":
            write(MIPMAP / "ic_launcher.xml", adaptive(key, shape))
            write(MIPMAP / "ic_launcher_round.xml", adaptive(key, shape))
        else:
            write(MIPMAP / f"ic_launcher_{key}.xml", adaptive(key, shape))
        print("wrote", key)


if __name__ == "__main__":
    main()
